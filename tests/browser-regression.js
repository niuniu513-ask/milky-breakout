(() => {
  const checks = [];
  function assert(ok, label) { if (!ok) throw new Error(label); checks.push(label); }
  settings.sound = false;
  newGame(); state = S.PLAY; showDlg(null);
  assert(level === 1 && lives === 3 && bricks.length === 24, 'new game');
  assert(document.activeElement.tagName !== 'BUTTON', 'game keyboard focus');
  const k = bricks[0];
  damageBrick(k, 99);
  const after = score, count = rescued;
  damageBrick(k, 99); destroyBrick(k);
  assert(score === after && rescued === count, 'removed brick cannot score twice');
  bullets.push({x: 20, y: 200});
  startLevel(2);
  assert(bullets.length === 0 && laserTimer === 0, 'level clears projectiles');
  keys.ArrowRight = true;
  pauseOnLeave();
  const before = paddle.x;
  update(1);
  assert(state === S.PAUSE && paddle.x === before && !keys.ArrowRight, 'auto pause clears keys');
  slowmoT = 0.5; loop(last + 20);
  assert(slowmoT === 0.5, 'pause freezes final slow motion');
  score = 1200; rescued = 40; endless = false; startLevel(5);
  levelClear();
  assert(progress.level === 6 && progress.endless === 1, 'final level saves endless checkpoint');
  resumeGame();
  assert(level === 6 && endless && score === 1200 && rescued === 40 && lives === 3 && stage === 2, 'endless checkpoint restores');
  newGame(); state = S.PLAY;
  const chain = bricks.slice(0, 3);
  chain.forEach(b => { b.boom = true; b.hp = b.maxHp = 1; });
  bricks = chain;
  damageBrick(chain[0], 1);
  assert(rescued === 3, 'chain explosion rescues each brick once');
  const savedRescued = rescued;
  chain.forEach(b => damageBrick(b, 2));
  assert(rescued === savedRescued, 'stale chain references ignored');
  bricks = []; balls = []; slowmoT = 0; lives = 1;
  update(1 / 120);
  assert(state === S.LEVELUP && lives === 1, 'last brick clear takes priority over ball loss');
  newGame(); state = S.PLAY; milkCharge = MILK_CHARGE_MAX;
  update(1 / 120);
  assert(milkShield && milkWaves.length === 1 && milkCharge === 0, 'charged milk assist activates');
  const hpBefore = bricks.reduce((sum, k) => sum + k.hp, 0);
  for (let i = 0; i < 150; i++) update(1 / 120);
  assert(bricks.reduce((sum, k) => sum + k.hp, 0) < hpBefore, 'milk wave damages crossed bricks');
  milkShield = true; const hearts = lives;
  loseLife();
  assert(lives === hearts && !milkShield && balls.length === 1 && balls[0].stuck, 'shield saves one lost volley');
  loseLife();
  assert(lives === hearts - 1, 'shield cannot save a second volley');
  startLevel(2);
  assert(!milkShield && milkCharge === 0 && milkWaves.length === 0, 'assist state resets across levels');
  clearProgress(); score = 0; rescued = 0; endless = false; level = 1; stage = 0;
  newGame(); clearProgress(); state = S.MENU; showDlg('dlgMenu');
  return { passed: checks.length, checks };
})()
